/**
 * 沖縄は本州から遠く離れているため、地図では点線の枠で囲った「別枠」に描く。
 * 枠の範囲（グリッド座標）。map-renderer.js がこの矩形を点線で描く。
 */
export const INSET_BOX = { col: 12, row: 34, cols: 5, rows: 4, label: "沖縄" };

/**
 * [row, colStart, colEnd] の区間リストを、マス座標の集合に展開する。
 * @param {number} prefectureId
 * @returns {Array<{col:number,row:number}>}
 */
export function cellsOf(prefectureId) {
  const spans = SPANS[prefectureId];
  if (!spans) return [];
  const cells = [];
  for (const [row, colStart, colEnd] of spans) {
    for (let col = colStart; col <= colEnd; col++) cells.push({ col, row });
  }
  return cells;
}

/**
 * 形状データの健全性チェック（開発時に main.js から呼ぶ）。
 * ・47県すべてに形があるか
 * ・同じマスを2つの県が奪い合っていないか
 * ・グリッドからはみ出していないか
 * ・指でタップできる大きさがあるか
 * @returns {string[]} 問題があればその説明。無ければ空配列
 */
export function validateShapes(prefectureIds) {
  const problems = [];
  const owner = new Map();   // "col,row" -> prefectureId

  for (const id of prefectureIds) {
    const cells = cellsOf(id);
    if (cells.length === 0) {
      problems.push(`id=${id} の形状データがありません`);
      continue;
    }
    if (cells.length < 3) {
      problems.push(`id=${id} が ${cells.length}マスしかありません（指でタップできません）`);
    }
    for (const { col, row } of cells) {
      if (col < 1 || col > GRID_COLS || row < 1 || row > GRID_ROWS) {
        problems.push(`id=${id} のマス(${col},${row})がグリッドの外です`);
      }
      const key = `${col},${row}`;
      if (owner.has(key)) {
        problems.push(`マス(${col},${row})を id=${owner.get(key)} と id=${id} が取り合っています`);
      }
      owner.set(key, id);
    }
  }
  return problems;
}
