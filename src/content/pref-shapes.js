/**
 * pref-shapes.js ― デフォルメ日本地図の形状データ。
 *
 * ■ 作り方
 *   このデータは手で置いたものではなく、`tools/generate-map.mjs` が
 *   実際の地理データから生成している。
 *     ・位置   … 各県の重心の緯度経度（県庁所在地ではない）
 *     ・大きさ … 実面積の平方根に比例（そのままだと東京が1マスになり押せない）
 *     ・形     … 実際の縦横比（長野は縦長、静岡は横長、石川は能登半島ぶん縦長）
 *     ・海     … 別の島どうしが辺で接しないよう、必ず1マス空ける
 *
 *   手で座標を置くと必ず位置がずれるので、直したいときも
 *   生成スクリプトの数値を変えて作り直すのが確実。
 *   （手順は docs/CUSTOMIZE.md「地図の形を直す」）
 *
 * ■ それでも手で微調整したいとき
 *   下の SPANS を直接編集してよい。[row, colStart, colEnd] が
 *   「その行の、この列からこの列まで」を表す。
 *   輪郭線は shape-builder.js が自動生成するので、パスを書く必要はない。
 *
 *   守ること:
 *     ・ひとつの県のマスは必ず「辺」でつながっていること（角だけの接触はNG）
 *     ・1県あたり3マス以上（指でタップできる大きさの下限）
 *     ・別の島（北海道・本州・四国・九州・沖縄）どうしを辺で接触させない
 *   いずれもテスト（tests/tests.js の「map ― 形状データの整合性」）が見張っている。
 *
 * ■ 座標系
 *   col: 1(西) → GRID_COLS(東)
 *   row: 1(北) → GRID_ROWS(南)
 */

